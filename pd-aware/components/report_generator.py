"""
PDF report generator for PD-Aware screening summaries.

Generates downloadable PDF reports containing screening results,
symptom information, model output, and appropriate disclaimers.

Does NOT include fabricated clinician names, hospital affiliations,
signatures, certifications, or approval seals.
"""

import io
import logging
from datetime import datetime, timezone
from typing import Dict, List, Optional

from fpdf import FPDF

from config.settings import MEDICAL_DISCLAIMER

logger = logging.getLogger(__name__)


class PDFReport(FPDF):
    """Custom PDF with header and footer for PD-Aware reports."""

    def __init__(self):
        super().__init__()
        self.set_auto_page_break(auto=True, margin=25)

    def header(self):
        self.set_font("Helvetica", "B", 14)
        self.set_text_color(41, 98, 155)  # Professional blue
        self.cell(0, 10, "PD-Aware Screening Report", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(
            0, 5,
            "AI-Assisted Screening - Not a Medical Diagnosis",
            align="C", new_x="LMARGIN", new_y="NEXT",
        )
        self.line(10, self.get_y() + 2, 200, self.get_y() + 2)
        self.ln(8)

    def footer(self):
        self.set_y(-20)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(128, 128, 128)
        clean_disclaimer = MEDICAL_DISCLAIMER[:120].replace("—", "-") + "..."
        self.cell(0, 4, clean_disclaimer, align="C", new_x="LMARGIN", new_y="NEXT")
        self.cell(0, 4, f"Page {self.page_no()}/{{nb}}", align="C")

    def section_title(self, title: str):
        self.set_font("Helvetica", "B", 12)
        self.set_text_color(41, 98, 155)
        safe_title = (
            str(title)
            .replace("•", "-")
            .replace("—", "-")
            .replace("–", "-")
            .replace("’", "'")
            .replace("“", '"')
            .replace("”", '"')
        )
        self.cell(0, 8, safe_title, new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(41, 98, 155)
        self.line(10, self.get_y(), 80, self.get_y())
        self.ln(4)

    def body_text(self, text: str):
        self.set_font("Helvetica", "", 10)
        self.set_text_color(50, 50, 50)
        # Sanitize common non-latin-1 characters
        safe_text = (
            str(text)
            .replace("•", "-")
            .replace("—", "-")
            .replace("–", "-")
            .replace("’", "'")
            .replace("“", '"')
            .replace("”", '"')
        )
        self.multi_cell(0, 5, safe_text)
        self.ln(2)

    def key_value(self, key: str, value: str):
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(70, 70, 70)
        self.cell(60, 6, f"{key}:")
        self.set_font("Helvetica", "", 10)
        self.set_text_color(50, 50, 50)
        safe_val = (
            str(value)
            .replace("•", "-")
            .replace("—", "-")
            .replace("–", "-")
            .replace("’", "'")
            .replace("“", '"')
            .replace("”", '"')
        )
        self.cell(0, 6, safe_val, new_x="LMARGIN", new_y="NEXT")

    def warning_box(self, text: str):
        self.set_fill_color(255, 248, 220)
        self.set_draw_color(200, 180, 100)
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(120, 100, 30)
        y = self.get_y()
        self.rect(10, y, 190, 20, style="DF")
        self.set_xy(15, y + 3)
        safe_text = (
            str(text)
            .replace("•", "-")
            .replace("—", "-")
            .replace("–", "-")
            .replace("’", "'")
            .replace("“", '"')
            .replace("”", '"')
        )
        self.multi_cell(180, 4, safe_text)
        self.set_y(y + 24)


def generate_screening_report(
    report_id: str,
    screening_data: Dict,
    prediction_data: Optional[Dict] = None,
    explanation_data: Optional[Dict] = None,
    include_symptoms: bool = True,
    include_prediction: bool = True,
    include_explanation: bool = True,
) -> bytes:
    """
    Generate a PDF screening report.

    Returns the PDF as bytes for download.
    """
    pdf = PDFReport()
    pdf.alias_nb_pages()
    pdf.add_page()

    # ─── Report Info ──────────────────────────────────────────────────────────
    pdf.section_title("Report Information")
    pdf.key_value("Report ID", report_id)
    pdf.key_value("Date", datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))
    pdf.key_value("Type", "AI-Assisted Screening Summary")
    pdf.ln(4)

    # ─── Important Notice ─────────────────────────────────────────────────────
    pdf.warning_box(
        "IMPORTANT: This report is generated by an AI screening tool and is NOT "
        "a medical diagnosis. It should be discussed with a qualified healthcare "
        "professional. Do not make medical decisions based solely on this report."
    )
    pdf.ln(4)

    # ─── Patient Information ──────────────────────────────────────────────────
    pdf.section_title("Patient Information")
    if screening_data.get("age_range"):
        pdf.key_value("Age Range", screening_data["age_range"])
    if screening_data.get("symptom_duration"):
        pdf.key_value("Symptom Duration", screening_data["symptom_duration"])
    if screening_data.get("existing_diagnosis"):
        pdf.key_value("Existing Diagnosis", screening_data["existing_diagnosis"])
    if screening_data.get("family_history"):
        pdf.key_value("Family History", screening_data["family_history"])
    pdf.ln(4)

    # ─── Reported Symptoms ────────────────────────────────────────────────────
    if include_symptoms:
        symptoms = screening_data.get("user_reviewed_symptoms") or screening_data.get("questionnaire_responses")
        if symptoms:
            pdf.section_title("Reported Symptoms")

            if isinstance(symptoms, list):
                for s in symptoms:
                    if isinstance(s, dict):
                        name = s.get("name", s.get("id", "Unknown"))
                        severity = s.get("severity", "reported")
                        pdf.body_text(f"• {name} — {severity}")
                    else:
                        pdf.body_text(f"• {s}")
            elif isinstance(symptoms, dict):
                for key, value in symptoms.items():
                    if value and value not in ("none", "Not present"):
                        pdf.body_text(f"• {key}: {value}")

            pdf.ln(2)

        # Natural language input
        nl_input = screening_data.get("natural_language_input")
        if nl_input:
            pdf.section_title("Patient's Description")
            pdf.body_text(f'"{nl_input}"')
            pdf.ln(2)

    # ─── Model Output ─────────────────────────────────────────────────────────
    if include_prediction and prediction_data and prediction_data.get("success"):
        pdf.section_title("Screening Result")

        label = prediction_data.get("prediction_label", "N/A")
        category = prediction_data.get("prediction_category", "N/A")
        score = prediction_data.get("prediction_score")

        if label == 1 or category == "parkinson":
            pdf.body_text(
                "The model identified patterns in the provided information that were "
                "more consistent with its Parkinson's-associated training examples."
            )
        else:
            pdf.body_text(
                "The model did not identify strong patterns associated with its "
                "Parkinson's training examples in the provided information."
            )

        pdf.ln(2)
        pdf.key_value("Model Output", category.title())
        if score is not None:
            pdf.key_value("Model Score", f"{score:.2%}")
            pdf.body_text(
                "Note: This score represents the model's internal confidence, "
                "not a clinical probability of having Parkinson's disease."
            )

        pdf.key_value("Model Version", prediction_data.get("model_version", "N/A"))
        pdf.key_value("Model Type", prediction_data.get("model_type", "N/A"))
        pdf.ln(4)

    # ─── Feature Explanations ─────────────────────────────────────────────────
    if include_explanation and explanation_data and explanation_data.get("success"):
        pdf.section_title("Contributing Factors")
        pdf.body_text(
            "The following features had the greatest influence on the model's output. "
            "Feature importance does not prove medical causation."
        )
        pdf.ln(2)

        top = explanation_data.get("top_contributors", [])[:5]
        for contrib in top:
            direction = contrib.get("direction", "")
            desc = contrib.get("description", contrib.get("feature", ""))
            magnitude = contrib.get("magnitude", 0)
            pdf.body_text(f"• {desc}: {direction} (magnitude: {magnitude:.3f})")

        pdf.ln(4)

    # ─── Limitations ──────────────────────────────────────────────────────────
    pdf.section_title("Important Limitations")
    limitations = [
        "This screening uses a model trained on a small dataset of 31 subjects.",
        "The model analyzes voice biomedical features, not clinical symptoms.",
        "Performance may not generalize to all populations or recording conditions.",
        "This is not a clinical diagnostic tool and has not been clinically validated.",
        "A positive screening result does not mean you have Parkinson's disease.",
        "A negative result does not rule out Parkinson's disease.",
    ]
    for lim in limitations:
        pdf.body_text(f"• {lim}")
    pdf.ln(4)

    # ─── Recommended Next Steps ───────────────────────────────────────────────
    pdf.section_title("Recommended Next Steps")
    pdf.body_text(
        "If you have persistent or concerning symptoms, consider discussing them "
        "with a qualified healthcare professional, such as a neurologist. Bring "
        "this report to your appointment for reference."
    )
    pdf.body_text(
        "Your healthcare provider can perform a comprehensive clinical evaluation "
        "that this screening tool cannot replace."
    )
    pdf.ln(4)

    # ─── Final Disclaimer ─────────────────────────────────────────────────────
    pdf.section_title("Disclaimer")
    pdf.body_text(MEDICAL_DISCLAIMER)
    pdf.body_text(
        "This report was generated by PD-Aware, an AI-assisted screening tool. "
        "It does not contain or represent the opinion of any specific healthcare "
        "professional or institution."
    )

    # Return as bytes
    return bytes(pdf.output())
